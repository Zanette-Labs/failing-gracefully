#!/usr/bin/env python3
"""Generate the site's sampled simplex paths using the paper figure's update rule.

This mirrors results/simplified_dynamics/compare_sampled_sgd_trajectories.py
from the paper source, with the site's requested c=0.6 and batch size 32.
"""

import json
from pathlib import Path

import numpy as np


CAUTION = 0.6
LEARNING_RATE = 0.1
STEPS = 100
SAMPLE_SIZE = 32
EPSILON = 1e-8
SEED = 0
INITIAL_SUCCESS_ERROR = [
    (0.01, 0.50),
    (0.03, 0.60),
    (0.05, 0.40),
    (0.07, 0.20),
    (0.20, 0.40),
    (0.30, 0.60),
    (0.01, 0.95),
]


def softmax(logits):
    shifted = logits - logits.max()
    values = np.exp(shifted)
    return values / values.sum()


def sampled_gradient(probabilities, counts, method):
    frequencies = counts / counts.sum()
    if method == "reinforce":
        weights = np.array([1.0, CAUTION, 0.0])
    else:
        non_error_weight = CAUTION / (counts[0] + counts[1] + EPSILON)
        weights = SAMPLE_SIZE * np.array([
            (1.0 - CAUTION) / (counts[0] + EPSILON) + non_error_weight,
            non_error_weight,
            0.0,
        ])
    advantages = weights - frequencies @ weights
    weighted = frequencies * advantages
    return weighted - weighted.sum() * probabilities


def optimize(initial, method, seed):
    logits = np.log(initial)
    logits -= logits.mean()
    trajectory = [softmax(logits).tolist()]
    rng = np.random.default_rng(seed)
    for _ in range(STEPS):
        probabilities = softmax(logits)
        counts = rng.multinomial(SAMPLE_SIZE, probabilities)
        logits += LEARNING_RATE * sampled_gradient(probabilities, counts, method)
        trajectory.append(softmax(logits).tolist())
    return trajectory


def main():
    initial_policies = [
        [success, 1.0 - success - error, error]
        for success, error in INITIAL_SUCCESS_ERROR
    ]
    # The paper reserves the first spawned stream to keep the other paths stable.
    seeds = np.random.SeedSequence(SEED).spawn(len(initial_policies) + 1)[1:]
    data = {
        "configuration": {
            "caution": CAUTION,
            "learningRate": LEARNING_RATE,
            "steps": STEPS,
            "sampleSize": SAMPLE_SIZE,
            "smoothing": EPSILON,
            "seed": SEED,
            "initialPolicies": initial_policies,
        },
        "trajectories": {
            method: [optimize(initial, method, seed)
                     for initial, seed in zip(initial_policies, seeds)]
            for method in ("reinforce", "graceful")
        },
    }
    destination = Path(__file__).resolve().parents[1] / "docs" / "simplex-data.js"
    destination.write_text(
        "// Generated by scripts/generate_simplex_trajectories.py.\n"
        + "export const simplexData = "
        + json.dumps(data, separators=(",", ":"), allow_nan=False)
        + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {destination}")


if __name__ == "__main__":
    main()
